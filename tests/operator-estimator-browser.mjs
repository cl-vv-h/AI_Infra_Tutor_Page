import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
import {readFile} from 'node:fs/promises'
const require=createRequire(import.meta.url)
const modulePath=process.env.MODEL_QA_PLAYWRIGHT || 'playwright'
const {chromium}=require(modulePath),{expect}=require(`${modulePath}/test`)
const base=process.env.MODEL_QA_BASE || 'http://127.0.0.1:4186/AI_Infra_Tutor_Page/'
const browser=await chromium.launch({headless:true,...(process.env.MODEL_QA_CHANNEL?{channel:process.env.MODEL_QA_CHANNEL}:{})})
try {
  for (const width of [360,390,768,1440]) {
    const page=await browser.newPage({viewport:{width,height:1000},reducedMotion:'reduce'})
    page.setDefaultTimeout(15000)
    const errors=[],requests=[]
    page.on('pageerror',e=>errors.push(e.message))
    page.on('request',r=>requests.push({method:r.method(),url:r.url()}))
    await page.route('**/*',route=>new URL(route.request().url()).origin===new URL(base).origin?route.continue():route.abort())
    const fit=async()=>assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`Overflow at ${width}`)
    await page.goto(`${base}#/`,{waitUntil:'networkidle'})
    await page.getByRole('link').filter({hasText:'算子耗时估算'}).click()
    await expect(page.getByRole('heading',{name:'算子耗时估算',exact:true})).toBeVisible()
    await expect(page.getByTestId('runtime-range')).toBeVisible()
    await expect(page.getByText(/此处 Cube 375/)).toBeVisible()
    await fit()
    const center=()=>page.getByTestId('runtime-central').innerText()
    const before=await center()
    await page.getByLabel('M · 输出行数',{exact:true}).fill('8192')
    await expect.poll(center).not.toBe(before)
    await page.getByLabel('M · 输出行数',{exact:true}).fill('')
    await expect(page.getByRole('alert')).toContainText('m 必须')
    await expect(page.getByTestId('runtime-range')).toHaveCount(0)
    await page.getByLabel('M · 输出行数',{exact:true}).fill('4096')
    for (const hardware of ['950pr','950pr-28','950dt','custom']) {
      await page.getByLabel('硬件配置',{exact:true}).selectOption(hardware)
      for(const precision of ['bf16','fp16','fp8','int8','mxfp4']) {
        await page.getByLabel('输入精度',{exact:true}).selectOption(precision)
        await expect(page.getByTestId('runtime-range')).toBeVisible()
        await fit()
      }
    }
    await page.getByLabel('硬件配置',{exact:true}).selectOption('910c')
    await expect(page.getByLabel('输入精度',{exact:true})).toHaveValue('bf16')
    await expect(page.getByLabel('输入精度',{exact:true}).locator('option[value=fp8]')).toHaveCount(0)
    await page.getByLabel('硬件配置',{exact:true}).selectOption('950dt')
    await page.getByLabel('算子类型',{exact:true}).selectOption('indexer')
    await page.getByLabel('Query 长度 Q',{exact:true}).fill('128')
    await page.getByLabel('右对齐 causal：只计算有效 Query–Key 对',{exact:true}).check()
    const noScores=await center()
    await page.getByLabel('将聚合 score [B,Q,S] 写入 HBM，再由 Top-K 读取',{exact:true}).check()
    await expect(page.getByTestId('runtime-range')).toBeVisible()
    assert.ok(noScores)
    await page.getByLabel('Top-K',{exact:true}).fill('999999')
    await expect(page.getByRole('alert')).toContainText('Top-K 不能大于')
    await page.getByLabel('Top-K',{exact:true}).fill('2048')
    const calibration=page.locator('details').filter({has:page.locator('summary').filter({hasText:'硬件参数与校准假设'})})
    await calibration.locator('summary').click()
    await expect(page.getByLabel('Cube 峰值 TFLOP/s',{exact:true})).toHaveValue('486')
    await expect(page.getByLabel('HBM 带宽 GB/s',{exact:true})).toHaveValue('4000')
    await page.getByLabel('Top-K 选择吞吐 Gcmp/s',{exact:true}).fill('0')
    await expect(page.getByRole('alert')).toContainText('选择吞吐')
    await page.getByLabel('Top-K 选择吞吐 Gcmp/s',{exact:true}).fill('50')
    await page.getByLabel('可用容量 GB',{exact:true}).fill('0.001')
    await expect(page.getByRole('alert')).toContainText('所列张量超过')
    await page.getByLabel('实测耗时',{exact:true}).fill('100000')
    await expect(page.getByTestId('runtime-comparison')).toContainText('容量')
    await page.getByLabel('可用容量 GB',{exact:true}).fill('144')
    await page.getByLabel('实测耗时',{exact:true}).fill('12345.6789')
    await expect(page.getByTestId('runtime-comparison')).toContainText('高于当前情景区间')
    const comp=await page.getByTestId('runtime-comparison').innerText()
    await page.getByLabel('时间单位',{exact:true}).selectOption('ms')
    await page.getByLabel('实测耗时',{exact:true}).fill('12.3456789')
    await expect(page.getByTestId('runtime-comparison')).toHaveText(comp,{useInnerText:true})
    const downloadPromise=page.waitForEvent('download')
    await page.getByRole('button',{name:'导出估算 JSON',exact:true}).click()
    const download=await downloadPromise
    const output=await readFile(await download.path(),'utf8'),report=JSON.parse(output)
    assert.equal(report.input.operator,'indexer')
    assert.equal(report.input.materialize,true)
    assert.equal(report.hardwareId,'950dt')
    assert.ok(!output.includes('12345.6789')&&!output.includes('12.3456789'))
    assert.deepEqual(Object.keys(report).sort(),['schema','version','hardwareId','input','result','notice'].sort())
    assert.equal(new URL(page.url()).search,'')
    assert.equal(new URL(page.url()).hash,'#/operators')
    assert.ok(requests.every(r=>r.method==='GET'),'No data POSTs')
    for(const op of ['rmsnorm','softmax','gather']) {
      await page.getByLabel('算子类型',{exact:true}).selectOption(op)
      await expect(page.getByTestId('runtime-range')).toBeVisible()
      await fit()
    }
    await page.getByRole('button',{name:'重置全部',exact:true}).click()
    await expect(page.getByLabel('硬件配置',{exact:true})).toHaveValue('910c')
    await expect(page.getByLabel('实测耗时',{exact:true})).toHaveValue('')
    await calibration.locator('summary').click()
    await page.evaluate(()=>scrollTo(0,0))
    if(process.env.MODEL_QA_SCREENSHOTS)await page.screenshot({path:`${process.env.MODEL_QA_SCREENSHOTS}/operators-${width}.png`,fullPage:true})
    await page.reload({waitUntil:'networkidle'})
    await expect(page.getByRole('heading',{name:'算子耗时估算',exact:true})).toBeVisible()
    await fit()
    assert.deepEqual(errors,[])
    await page.close()
    console.log(`Operator estimator passed at ${width}px: hardware/dtypes/operators, validation, calibration, measurements, export privacy, route reload, no overflow.`)
  }
} finally {await browser.close()}
