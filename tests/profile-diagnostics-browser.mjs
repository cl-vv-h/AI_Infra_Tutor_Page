    const region=page.getByRole('region',{name:'单份采样诊断',exact:true})
    await expect(region).toBeVisible()
    await expect(page.getByTestId('phase-prefill-wall')).toHaveText('未知')
    await expect(page.getByTestId('phase-scheduling')).toHaveText('未知')
    await page.getByLabel('Host 标记线程',{exact:true}).selectOption('pid:1/tid:0')
    await page.getByLabel('我已确认所选 Host 线程',{exact:false}).check()
    await page.getByRole('button',{name:'应用诊断设置',exact:true}).click()
    await expect(page.getByTestId('phase-prefill-wall')).toHaveAttribute('data-us','2000')
    await expect(page.getByTestId('phase-decode-wall')).toHaveAttribute('data-us','3550')
    await expect(page.getByTestId('phase-scheduling')).toHaveAttribute('data-us','800')
    await expect(page.getByTestId('decode-step-statistics')).toContainText('627.5 µs')
    await expect(page.getByRole('figure',{name:'Prefill 算子累计耗时占比图',exact:true})).toContainText('64.86%')
    await page.getByLabel('观察阶段',{exact:true}).selectOption('decode')
    await expect(page.getByRole('figure',{name:'Decode 算子累计耗时占比图',exact:true})).toContainText('78.08%')
    await expect(page.getByRole('region',{name:'低活跃算子清单',exact:true})).toContainText('9 / 9')
    await fit()
    await page.getByRole('region',{name:'阶段计时',exact:true}).scrollIntoViewIfNeeded()
    if(process.env.MODEL_QA_SCREENSHOTS)await page.screenshot({path:join(process.env.MODEL_QA_SCREENSHOTS,`single-profile-stages-${width}.png`)})
    await page.getByRole('region',{name:'低活跃算子清单',exact:true}).scrollIntoViewIfNeeded()
    if(process.env.MODEL_QA_SCREENSHOTS)await page.screenshot({path:join(process.env.MODEL_QA_SCREENSHOTS,`single-profile-utilization-${width}.png`)})
    await page.getByText('设置阶段来源与计数器口径',{exact:true}).click()
    await page.getByLabel('Prefill 标记',{exact:true}).selectOption('decode')
    await page.getByLabel('Decode 标记',{exact:true}).selectOption('decode')
    await page.getByRole('button',{name:'应用诊断设置',exact:true}).click()
    await expect(page.getByRole('alert')).toContainText('同一个事件名称')
    // Invalid configuration is recoverable without reimporting the raw file.
    await page.getByLabel('Prefill 标记',{exact:true}).selectOption('prefill')
    await page.getByRole('button',{name:'应用诊断设置',exact:true}).click()
    await expect(page.getByRole('alert')).toHaveCount(0)
    await expect(page.getByTestId('phase-prefill-wall')).toHaveAttribute('data-us','2000')
    const csv='Name,Type,Start Time(us),Duration(us),aic_mac_ratio,aiv_vec_ratio\nPRIVATE_OP,MatMul,100,20,0.1,\nN,RmsNorm,120,20,,0.2\nPRIVATE_OP,MatMul,150,10,N/A,'
    await page.getByLabel('导入基线 A',{exact:true}).setInputFiles({name:'PRIVATE_PROFILE.csv',mimeType:'text/csv',buffer:Buffer.from(csv)})
    await expect(page.getByTestId('phase-prefill-wall')).toHaveText('未知')
    await page.getByLabel('Ratio 单位',{exact:true}).selectOption('fraction')
    await page.getByText('手动标注阶段（覆盖自动标记）',{exact:true}).click()
    await page.getByLabel('阶段起点',{exact:true}).fill('0')
    await page.getByLabel('阶段终点',{exact:true}).fill('40')
    await page.getByRole('button',{name:'添加阶段',exact:true}).click()
