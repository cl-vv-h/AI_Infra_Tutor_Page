import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { join } from 'node:path'
const require=createRequire(import.meta.url)
const modulePath=process.env.MODEL_QA_PLAYWRIGHT || 'playwright'
const {chromium}=require(modulePath),{expect}=require(`${modulePath}/test`)
const base=process.env.MODEL_QA_BASE || 'http://127.0.0.1:4185/AI_Infra_Tutor_Page/'
const browser=await chromium.launch({headless:true,...(process.env.MODEL_QA_CHANNEL?{channel:process.env.MODEL_QA_CHANNEL}:{})})
try {
  for(const width of [360,390,768,1440]) {
    const page=await browser.newPage({viewport:{width,height:900},reducedMotion:'reduce'})
    const errors=[];page.on('pageerror',e=>errors.push(e.message))
    await page.route('**/*',route=>new URL(route.request().url()).origin===new URL(base).origin?route.continue():route.abort())
    page.setDefaultTimeout(15000)
    const fit=async()=>assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
    await page.goto(`${base}#/models/glm-5-2?view=weights&layer=3&tp=8&ep=4&pp=4&stage=0&adp=4&replicas=2&precision=mixed`,{waitUntil:'networkidle'})
    const result=page.getByLabel('实时权重结果',{exact:true})
    const value=async key=>Number(await page.getByTestId(`weight-${key}`).getAttribute('data-bytes'))
    await expect(page.getByLabel('Pipeline PP',{exact:true})).toHaveValue('4')
    await expect(result).toContainText('64 卡')
    const fleet=await value('fleet'),current=await value('current')
    assert.ok(current>0&&fleet>current)
    await page.getByLabel('观察 PP 阶段',{exact:true}).selectOption('3')
    await expect.poll(()=>value('current')).not.toBe(current)
    assert.equal(await value('fleet'),fleet)
    await expect(page.getByRole('status').filter({hasText:'此层不在'})).toBeVisible()
    await page.getByLabel('独立 DP 副本',{exact:true}).selectOption('1')
    await expect.poll(()=>value('fleet')).toBe(fleet/2)
    const editor=page.getByLabel('逐权重精度',{exact:true})
    await editor.locator(':scope > summary').click()
    await editor.getByLabel('精度覆盖范围',{exact:true}).selectOption('layer')
    await editor.getByLabel('精度权重模块',{exact:true}).selectOption('moe')
    const oldLocal=await value('current')
    await editor.getByLabel('experts.down_proj 权重格式',{exact:true}).selectOption('int8')
    await expect.poll(()=>value('fleet')).toBeLessThan(fleet/2)
    assert.equal(await value('current'),oldLocal,'non-owned layer must not affect selected stage')
    const box=await result.boundingBox()
    assert.ok(box.y>=0&&box.y+box.height<900,'results remain visible while editing precision')
    await fit()
    if(process.env.MODEL_QA_SCREENSHOTS) await page.screenshot({path:join(process.env.MODEL_QA_SCREENSHOTS,`workbench-edit-${width}.png`)})
    const saved=page.url();await page.reload({waitUntil:'networkidle'});await expect(page).toHaveURL(saved)
    await expect(page.getByLabel('Attention DP',{exact:true})).toHaveValue('4')
    await page.getByLabel('每阶段 TP',{exact:true}).selectOption('2')
    await expect(page.getByLabel('Expert EP',{exact:true})).toHaveValue('1')
    await expect(page.getByLabel('Attention DP',{exact:true})).toHaveValue('1')
    await page.getByLabel('直接输入层号',{exact:true}).fill('12')
    await expect(page).toHaveURL(/layer=12(?:&|$)/)
    await page.getByRole('tab',{name:'结构图',exact:true}).click()
    const overview=page.getByRole('region',{name:'模型核心结构',exact:true})
    await expect(overview).toBeVisible()
    await expect(page.locator('#model-full-diagram')).not.toHaveAttribute('open','')
    await overview.getByRole('button').filter({hasText:'Sparse MoE'}).click()
    await expect(page.getByRole('dialog',{name:'模块详情',exact:true})).toBeVisible()
    await page.getByRole('button',{name:'关闭模块详情',exact:true}).click()
    const fullDiagram=page.locator('#model-full-diagram')
    await fullDiagram.locator(':scope > summary').focus()
    await page.keyboard.press('Enter')
    await expect(fullDiagram).toHaveAttribute('open','')
    await page.keyboard.press('Enter')
    await expect(fullDiagram).not.toHaveAttribute('open','')
    await page.getByRole('tab',{name:'缓存容量',exact:true}).click()
    const cache=page.getByRole('region',{name:'缓存核心计算',exact:true})
    await expect(cache).toBeVisible()
    const oldCache=await cache.locator('output').innerText()
    await page.getByLabel('缓存请求数',{exact:true}).selectOption('8')
    await expect(cache.locator('output')).not.toHaveText(oldCache)
    await fit()
    if(process.env.MODEL_QA_SCREENSHOTS) {
      for(const view of ['diagram','cache','weights']) {
        await page.goto(`${base}#/models/glm-5-2?view=${view}&layer=3&tp=8&ep=4&pp=4&adp=4&precision=mixed`,{waitUntil:'networkidle'})
        await expect(page.locator(`#workspace-tab-${view}`)).toHaveAttribute('aria-selected','true')
        await expect(page.locator(`#workspace-panel-${view}`)).toBeVisible()
        await page.evaluate(()=>scrollTo(0,0))
        await page.screenshot({path:join(process.env.MODEL_QA_SCREENSHOTS,`workbench-${view}-${width}.png`),animations:'disabled'})
      }
    }
    assert.deepEqual(errors,[])
    await page.close()
    console.log(`Compact workbench passed at ${width}px: topology, stage ownership, overrides, sticky results, URL, modal, cache.`)
  }
} finally {await browser.close()}
